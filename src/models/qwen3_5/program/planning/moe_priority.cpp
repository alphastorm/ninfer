std::span<const std::uint32_t> default_expert_priority(const TextConfig& config,
                                                       std::size_t layer) {
    const auto* moe = std::get_if<MoeConfig>(&config.ffn);
    if (config.architecture != Architecture::Qwen3_5Moe || config.hidden_size != 2048 ||
        config.num_hidden_layers != k35bExpertPriority.size() || !moe || moe->num_experts != 256 ||
        moe->num_experts_per_tok != 8 || moe->moe_intermediate_size != 512 ||
        moe->shared_expert_intermediate_size != 512 || layer >= k35bExpertPriority.size())
        return {};
    return k35bExpertPriority[layer];
}

